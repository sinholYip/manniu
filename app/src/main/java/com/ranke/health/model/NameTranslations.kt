private val exerciseChineseNames: Map<String, String> by lazy {
    exerciseEnglishNames.entries.reversed().associate { (cn, en) -> en.lowercase() to cn }
}

private val foodChineseNames: Map<String, String> by lazy {
    foodEnglishNames.entries.reversed().associate { (cn, en) -> en.lowercase() to cn }
}

fun exerciseDisplayName(name: String, english: Boolean): String =
    if (english) exerciseEnglishNames[name] ?: name else name

fun foodDisplayName(name: String, english: Boolean): String =
    if (english) foodEnglishNames[name] ?: name else name

fun sourceDisplayName(source: String, english: Boolean): String =
    if (english) sourceEnglishNames[source] ?: source else source

/** 把英文界面里显示的名称还原成中文数据键；未命中的自定义名称原样返回。 */
fun canonicalExerciseName(display: String, english: Boolean): String =
    if (english) exerciseChineseNames[display.trim().lowercase()] ?: display.trim() else display.trim()

fun canonicalFoodName(display: String, english: Boolean): String =
    if (english) foodChineseNames[display.trim().lowercase()] ?: display.trim() else display.trim()
